function DemoCanvas({ edge, onEdge }: { edge: number; onEdge: (i: number) => void }) {
  const ref = useRef<HTMLDivElement>(null);
  const [size, setSize] = useState({ w: 0, h: 0 });
  useLayoutEffect(() => {
    const el = ref.current!;
    const ro = new ResizeObserver(([e]) => setSize({ w: e.contentRect.width, h: e.contentRect.height }));
    ro.observe(el);
    return () => ro.disconnect();
  }, []);
  // Narrow windows get a calmer drawing: no default selection, room for the outside pills.
  const compact = size.w > 0 && size.w < 520;
  const [touched, setTouched] = useState(false);
  const view: ViewXf = useMemo(() => {
    const b = bbox(DEMO.outline);
    // The right side carries the overall-height pill, so it gets more room than the left.
    const padL = compact ? 58 : Math.max(70, size.w * 0.16);
    const padR = compact ? 96 : padL;
    const padY = compact ? 78 : Math.max(70, size.h * 0.17);
    const bw = b.maxX - b.minX, bh = b.maxY - b.minY;
    const z = Math.max(0.1, Math.min((size.w - padL - padR) / bw, (size.h - padY * 2) / bh));
    return { z, tx: padL + (size.w - padL - padR - bw * z) / 2 - b.minX * z, ty: size.h / 2 + ((b.minY + b.maxY) / 2) * z + 6 };
  }, [size, compact]);
  return (
    <div
      ref={ref}
      className="pw-canvas"
      onPointerOver={(e) => {
        const t = e.target as SVGElement;
        if (t.dataset.hit === 'edge') {
          setTouched(true);
          onEdge(Number(t.dataset.index));
        }
      }}
    >
      {size.w > 0 && (
        <svg width={size.w} height={size.h} role="img" aria-label={`Plan view of the sample bracket, edge E${edge + 1} selected`}>
          <Drawing width={size.w} height={size.h} view={view} part={DEMO} units="mm" selectedEdge={compact && !touched ? null : edge} selectedHole={null} showHoleLabels={!compact} showVertices={false} />
        </svg>
      )}
    </div>
  );
}
